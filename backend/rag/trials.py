"""Deterministic analytics over the ClinicalTrials.gov rows (counts are calculated, never generated)."""
from __future__ import annotations

from collections import Counter
from typing import Any

from backend.rag.index import KnowledgeBase

TOPIC_WORDS = {
    "COVID-19": ("covid", "sars-cov-2", "coronavirus", "long covid"),
    "Diabetes": ("diabetes", "diabetic", "glycemic", "insulin", "glucose", "hba1c"),
    "Heart attack": ("heart attack", "myocardial", "cardiac", "coronary", "heart disease", "heart"),
    "Knee injuries": ("knee", "acl", "meniscus", "arthroplasty"),
}
STATUSES = ("RECRUITING", "COMPLETED", "TERMINATED", "WITHDRAWN", "NOT_YET_RECRUITING", "ACTIVE_NOT_RECRUITING",
            "ENROLLING_BY_INVITATION", "SUSPENDED", "UNKNOWN")


def detect_topic(text: str) -> str | None:
    t = text.lower()
    for topic, words in TOPIC_WORDS.items():
        if any(w in t for w in words):
            return topic
    return None


def detect_status(text: str) -> str | None:
    t = text.lower().replace("-", " ")
    if "not yet recruiting" in t:
        return "NOT_YET_RECRUITING"
    for s in STATUSES:
        if s.lower().replace("_", " ") in t:
            return s
    return None


def detect_phase(text: str) -> str | None:
    t = text.lower()
    for n in ("4", "3", "2", "1"):
        if f"phase {n}" in t or f"phase{n}" in t or f"phase-{n}" in t:
            return f"PHASE{n}"
    return None


def query_trials(kb: KnowledgeBase, query: str, topic: str | None = None, status: str | None = None,
                 phase: str | None = None, top_k: int = 5) -> dict[str, Any]:
    idx = kb.indexes.get("clinical_trials")
    if idx is None:
        raise LookupError("clinical trials index not built")
    topic = topic or detect_topic(query)
    status = status or detect_status(query)
    phase = phase or detect_phase(query)

    def keep(c) -> bool:
        m = c.metadata
        if topic and topic not in m.get("topics", [m.get("topic")]):
            return False
        if status and m.get("status") != status:
            return False
        if phase and phase not in (m.get("phases") or ""):
            return False
        return True

    from backend.rag.index import SearchHit

    has_filters = any((topic, status, phase))
    allowed = {i for i, c in enumerate(idx.chunks) if keep(c)} if has_filters else set(range(len(idx.chunks)))
    population = [idx.chunks[i] for i in sorted(allowed)]
    ranked = idx.bm25.search(query, top_k, allowed if has_filters else None) if allowed else []
    hits = [SearchHit(idx.chunks[d], s, r, None, idx.bm25.matched_terms(query, idx.chunks[d].text))
            for r, (d, s) in enumerate(ranked, start=1)]
    if not hits and population:
        hits = [SearchHit(c, 0.0) for c in population[:top_k]]
    status_counts = Counter(c.metadata.get("status", "UNKNOWN") for c in population)
    phase_counts = Counter((c.metadata.get("phases") or "NA") for c in population)
    sponsors = Counter(c.metadata.get("sponsor", "") for c in population if c.metadata.get("sponsor"))
    funder = Counter(c.metadata.get("funder_type", "") for c in population if c.metadata.get("funder_type"))
    return {
        "filters_applied": {"topic": topic, "status": status, "phase": phase},
        "population_size": len(population),
        "status_counts": dict(status_counts.most_common(8)),
        "phase_counts": dict(phase_counts.most_common(8)),
        "top_sponsors": dict(sponsors.most_common(5)),
        "funder_types": dict(funder.most_common(5)),
        "matching_trials": [h.to_evidence(500) for h in hits],
        "value_type": "calculated",
        "note": "Counts are computed from the supplied ClinicalTrials.gov CSV exports, not generated by a model.",
    }
